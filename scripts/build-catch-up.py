#!/usr/bin/env python3
"""Builds supabase/repair/catch_up.sql: grants + every missing migration (guarded) + replay of table-level revokes."""
import pathlib, re
root = pathlib.Path(__file__).resolve().parent.parent
mig = sorted((root / "supabase/migrations").glob("*.sql"))
# marker = SQL boolean that is TRUE when the migration is already applied. None = idempotent, always run.
MARK = {
  "0001": "to_regclass('public.employees') is not null", "0002": "to_regclass('public.attendance_events') is not null",
  "0003": "to_regclass('public.performance_policies') is not null", "0004": "to_regclass('public.leads') is not null",
  "0005": "to_regclass('public.payroll_adjustments') is not null", "0006": "to_regclass('public.role_settings') is not null",
  "0007": "to_regclass('public.notification_preferences') is not null", "0008": "to_regclass('public.candidates') is not null",
  "0009": "to_regclass('public.employee_documents') is not null", "0010": "to_regclass('public.vendors') is not null",
  "0011": "to_regclass('public.project_milestones') is not null", "0012": "to_regclass('public.chat_message_reports') is not null",
  "0013": "exists(select 1 from pg_proc where proname='seed_executive_permissions')", "0014": "to_regclass('public.org_teams') is not null",
  "0015": "to_regclass('public.calendar_provider_connections') is not null", "0016": "to_regclass('public.workflow_rules') is not null",
  "0017": "exists(select 1 from pg_trigger where tgname='workflow_rule_actions_validate')",
  "0018": "to_regclass('public.integration_check_runs') is not null",
  "0019": "exists(select 1 from pg_proc where proname='can_access_chat_realtime_topic')",
  "0020": "to_regclass('public.workflow_runs_sla_lookup_idx') is not null",
  "0021": "to_regclass('public.workflow_approval_cases') is not null",
  "0022": None, "0023": "to_regclass('public.whatsapp_optins') is not null", "0024": None, "0025": None,
  "0026": None, "0027": None, "0028": None, "0029": None, "0030": None, "0031": None, "0032": None, "0033": None, "0034": None, "0035": None, "0036": None, "0037": None, "0038": None, "0039": None, "0040": None, "0041": None, "0042": None, "0043": None, "0044": None,
}
out = ["""-- =============================================================================
-- VSM Ops — CATCH-UP & REPAIR (generated by scripts/build-catch-up.py). Paste the whole file into
-- Supabase → SQL Editor → Run. Safe to run more than once.
--   1. Gives the app's signed-in role (authenticated) and server role (service_role) access to the tables.
--      Row Level Security still decides WHICH rows each person sees. anon (logged-out) gets no table access.
--   2. Applies every migration that is missing, in order (already-applied ones are skipped).
--   3. Re-applies every table/column restriction from the migrations (e.g. webhook secrets stay unreadable).
-- If anything fails, the whole script is rolled back — nothing is left half-done.
-- =============================================================================
begin;
grant usage on schema public to authenticated, service_role;
grant select, insert, update, delete on all tables in schema public to authenticated;
grant all on all tables in schema public to service_role;
grant usage, select on all sequences in schema public to authenticated, service_role;
alter default privileges in schema public grant select, insert, update, delete on tables to authenticated;
alter default privileges in schema public grant all on tables to service_role;
alter default privileges in schema public grant usage, select on sequences to authenticated, service_role;
create table if not exists public._vsm_migrations (name text primary key, applied_at timestamptz not null default now());
alter table public._vsm_migrations enable row level security;
revoke all on public._vsm_migrations from anon, authenticated;
"""]
replay = []
for f in mig:
    v = f.name[:4]
    if v not in MARK: raise SystemExit(f"no marker for {f.name} — add one to MARK")
    body = f.read_text()
    tag = f"$vsm_{v}$"
    assert tag not in body
    cond = MARK[v]
    guard = f"if {cond} then raise notice 'skip {f.name} (already applied)'; else" if cond else "begin"
    end = "end if;" if cond else "end;"
    out.append(f"""
-- ▸ {f.name}
do $outer_{v}$ begin
  {guard}
    raise notice 'apply {f.name}';
    execute {tag}
{body}
{tag};
    insert into public._vsm_migrations(name) values ('{f.name}') on conflict do nothing;
  {end}
end $outer_{v}$;""")
    # collect table-level revoke/grant statements (not functions/schemas/default privileges)
    for stmt in re.findall(r"(?ims)^\s*((?:revoke|grant)\s[^;]*?;)", body):
        s = stmt.strip()
        if re.search(r"\b(function|schema|execute|sequence|procedure|routine)\b", s, re.I): continue
        if re.match(r"(?i)^grant\s+execute", s): continue
        replay.append((f.name, s))
out.append("\n-- ▸ Re-apply table and column restrictions from all migrations (in order)")
for name, s in replay:
    q = s.replace("$", "")
    out.append(f"do $r$ begin execute $q${s}$q$; exception when undefined_table or undefined_column or undefined_object then null; end $r$; -- {name}")
out.append("""
-- Logged-out visitors never read tables directly.
revoke all on all tables in schema public from anon;
commit;
select 'catch-up complete — now run supabase/diagnostics/health_check.sql' as result;
""")
(root / "supabase/repair").mkdir(exist_ok=True)
(root / "supabase/repair/catch_up.sql").write_text("\n".join(out))
print("written", len(mig), "migrations,", len(replay), "restrictions replayed")
