# VSM Ops — run everything locally on Windows with Docker Desktop.
#   1. Starts Supabase (Postgres, Auth, Realtime, Storage, Studio, mail catcher) in Docker
#   2. Applies every migration in supabase/migrations
#   3. Writes local keys to .env.local (or .env.docker.local if you already have a .env.local — never overwritten)
#   4. Creates the one Super Admin (first run only)
# Usage (PowerShell, in the project folder):  ./scripts/local-up.ps1 -Email you@vsmgrowth.com -Name "Your Name"
param([string]$Email = "", [string]$Name = "Super Admin")
$ErrorActionPreference = "Stop"

docker info *> $null
if ($LASTEXITCODE -ne 0) { Write-Host "Docker Desktop is not running. Start it and run this again." -ForegroundColor Red; exit 1 }
if (-not (Test-Path node_modules)) { npm install }

Write-Host "▸ Starting Supabase in Docker (first run downloads images, ~3–5 min)…" -ForegroundColor Cyan
npx supabase@latest start
if ($LASTEXITCODE -ne 0) { exit 1 }

$status = npx supabase@latest status -o env | Out-String
function Get-Val($k) { if ($status -match "(?m)^$k=`"?([^`"\r\n]+)") { return $Matches[1] } return "" }
$api = Get-Val "API_URL"; $anon = Get-Val "ANON_KEY"; $service = Get-Val "SERVICE_ROLE_KEY"
$mail = Get-Val "INBUCKET_URL"; if (-not $mail) { $mail = Get-Val "MAILPIT_URL" }; if (-not $mail) { $mail = "http://127.0.0.1:54324" }

$target = if (Test-Path .env.local) { ".env.docker.local" } else { ".env.local" }
@"
# Generated by scripts/local-up.ps1 for the LOCAL Docker stack only.
NEXT_PUBLIC_SUPABASE_URL=$api
NEXT_PUBLIC_SUPABASE_ANON_KEY=$anon
SUPABASE_SERVICE_ROLE_KEY=$service
APP_URL=http://localhost:3000
ORG_SLUG=vsm-growth
CRON_SECRET=local-$(Get-Random)
DEMO_EMAIL_DOMAIN=demo.vsmgrowth.com
"@ | Set-Content -Encoding utf8 $target
Write-Host "▸ Local keys written to $target" -ForegroundColor Green
if ($target -eq ".env.docker.local") { Write-Host "  (Your existing .env.local was NOT touched. To use Docker, temporarily rename it and rename .env.docker.local to .env.local.)" -ForegroundColor Yellow }

if ($Email) { node scripts/local-bootstrap.mjs --email $Email --name "$Name" }
else { Write-Host "▸ Skipped Super Admin creation (pass -Email you@company.com on first run)." -ForegroundColor Yellow }

Write-Host ""
Write-Host "  Supabase Studio : http://127.0.0.1:54323" -ForegroundColor Cyan
Write-Host "  Local email     : $mail  (reset/invite emails land here)" -ForegroundColor Cyan
Write-Host "  Start the app   : npm run dev   →  http://localhost:3000" -ForegroundColor Cyan
Write-Host "  Stop everything : npx supabase stop" -ForegroundColor Cyan
